# 1. 얼음 틀의 크기 (세로, 가로) 입력받기
세로크기, 가로크기 = map(int, input().split())

# 2. 얼음 틀 모양(0과 1) 입력받아서 표(리스트)로 만들기
얼음틀 = []
for i in range(세로크기):
    # '00110'처럼 입력된 글자를 한 칸씩 쪼개서 리스트로 묶어줌
    한줄 = list(map(int, input())) 
    얼음틀.append(한줄)

# 3. 잉크가 번지듯 주변 구멍(0)을 찾아다니며 채우는 함수 만들기
def 잉크번지기(세로위치, 가로위치):
    # 만약 얼음 틀 바깥으로 삐져나가면 바로 멈춤 (False)
    if 세로위치 < 0 or 세로위치 >= 세로크기 or 가로위치 < 0 or 가로위치 >= 가로크기:
        return False
    
    # 만약 아직 안 가본 뚫려있는 구멍(0)을 발견했다면!
    if 얼음틀[세로위치][가로위치] == 0:
        # "여기는 이미 채웠음!" 하고 표시를 남김 (0을 1로 바꿈)
        얼음틀[세로위치][가로위치] = 1
        
        # 내친김에 상, 하, 좌, 우도 다 검사해서 알아서 다 채우라고 명령함
        잉크번지기(세로위치 - 1, 가로위치) # 위로 잉크 번짐
        잉크번지기(세로위치 + 1, 가로위치) # 아래로 잉크 번짐
        잉크번지기(세로위치, 가로위치 - 1) # 왼쪽으로 잉크 번짐
        잉크번지기(세로위치, 가로위치 + 1) # 오른쪽으로 잉크 번짐
        
        # 구멍 한 덩어리를 싹 다 채웠으니 성공(True)을 외침
        return True
    
    # 칸막이(1)를 만났거나 이미 채운 곳이면 멈춤 (False)
    return False

# 4. 처음부터 끝까지 돌면서 아이스크림 덩어리 개수 세기
아이스크림_개수 = 0

for i in range(세로크기):
    for j in range(가로크기):
        # 만약 새로운 빈 덩어리를 찾아서 잉크 채우기에 성공했다면, 아이스크림 1개 완성!
        if 잉크번지기(i, j) == True:
            아이스크림_개수 += 1

# 최종 정답 출력
print(아이스크림_개수)
