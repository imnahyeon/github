# 1. 미로 크기(세로, 가로) 입력받기
세로크기, 가로크기 = map(int, input().split())

# 2. 미로 지도 모양(0과 1) 쪼개서 표로 만들기
미로 = []
for i in range(세로크기):
    한줄 = list(map(int, input()))
    미로.append(한줄)

# 3. 움직일 수 있는 4가지 방향 (상, 하, 좌, 우)
이동_세로 = [-1, 1, 0, 0]
이동_가로 = [0, 0, -1, 1]

# 4. 레퍼런스의 BFS(너비우선탐색) 원리 적용하기!
def 탈출구_찾기(세로, 가로):
    # 어려운 모듈 대신 파이썬 기본 '리스트'로 대기열(Queue) 만들기
    대기열 = []
    대기열.append((세로, 가로)) # 출발점을 대기열에 줄 세움
    
    while len(대기열) > 0: # 대기열에 갈 곳이 남아있다면 계속 반복
        # pop(0) : 대기열 맨 앞에 있는(가장 먼저 줄 선) 위치를 꺼냄
        현재_세로, 현재_가로 = 대기열.pop(0)
        
        # 4방향 찔러보기
        for i in range(4):
            다음_세로 = 현재_세로 + 이동_세로[i]
            다음_가로 = 현재_가로 + 이동_가로[i]
            
            # 미로 밖으로 삐져나가면 무시
            if 다음_세로 < 0 or 다음_세로 >= 세로크기 or 다음_가로 < 0 or 다음_가로 >= 가로크기:
                continue
            # 괴물(0)이 있으면 무시
            if 미로[다음_세로][다음_가로] == 0:
                continue
            
            # 한 번도 안 가본 정상적인 길(1)이라면
            if 미로[다음_세로][다음_가로] == 1:
                # 지금 위치에 적힌 걸음 수 + 1을 다음 칸 바닥에 덮어씀 (최단거리 누적)
                미로[다음_세로][다음_가로] = 미로[현재_세로][현재_가로] + 1
                
                # 방금 밟은 곳을 대기열 맨 뒤에 줄 세움
                대기열.append((다음_세로, 다음_가로))
                
    # 도착 지점(오른쪽 맨 아래) 바닥에 적혀 있는 최종 걸음 수를 반환
    return 미로[세로크기 - 1][가로크기 - 1]

# (0, 0) 첫 번째 칸부터 시작해서 정답 출력
print(탈출구_찾기(0, 0))
